# จำค่าที่ติ๊กล่าสุดไว้ใช้กับงานถัดไป (ผู้ใช้สั่ง: "จำค่าเดิมไว้")
PREFS_FILE = studio_shared.DATA_DIR / "clip_prefs.json"


def menu() -> list[dict]:
    """รายการช่องติ๊กให้หน้าเว็บวาด (ไม่ส่งข้อความคำสั่งไปด้วย ยาวเปล่าๆ)"""
    return [{"key": FULL_SHOT_KEY, "label": FULL_SHOT_LABEL, "hint": FULL_SHOT_HINT}]


def clean(raw) -> bool:
    """ค่าที่หน้าเว็บส่งมา → จริง/เท็จ"""
    return bool(raw)


def last_used() -> bool:
    """ติ๊กไว้ไหมในงานล่าสุด — ใช้เป็นค่าตั้งต้นของงานที่ยังไม่เคยเลือก"""
    try:
        data = json.loads(PREFS_FILE.read_text(encoding="utf-8"))
        return bool(data.get("full_shot"))
    except Exception:                                        # noqa: BLE001
        return False


def remember(value: bool) -> None:
    """จดว่าติ๊กหรือไม่ **ห้ามทำให้งานหลักล้ม** ถ้าจดไม่ได้ก็ปล่อย

    ใช้ `update_json` เพราะเซิร์ฟเวอร์สองตัว (8866/8877) แตะไฟล์เดียวกัน
    ถ้าอ่าน-แก้-เขียนเองจะมีจังหวะที่เขียนทับกันแล้วค่าหาย
    """
    def mutate(data: dict) -> dict:
        if not isinstance(data, dict):
            data = {}
        data["full_shot"] = bool(value)
        return data

    try:
        studio_shared.update_json(PREFS_FILE, mutate)
    except Exception:                                        # noqa: BLE001
        pass


def full_shot_of(run: dict) -> bool:
    """งานใบนี้ติ๊กไว้ไหม — ยังไม่เคยแตะเลยก็ใช้ค่าที่จำไว้ล่าสุด

    เก็บเป็นของงานแต่ละใบ ไม่ใช่ค่ารวมของทั้งระบบ เพราะสินค้าคนละชิ้นต้องการคนละแบบ
    ส่วนค่าที่จำไว้เป็นแค่ **ค่าตั้งต้น** ให้ไม่ต้องติ๊กซ้ำทุกใบ
    """
    picked = (run or {}).get("story_full_shot")
    return last_used() if picked is None else bool(picked)


def ask_of(run: dict) -> tuple[str, str]:
    """คืน (ชื่อกติกา, ข้อความที่จะใส่ลงคำขอ) — ไม่ติ๊กคืนค่าว่างทั้งคู่"""
    if full_shot_of(run):
        return FULL_SHOT_LABEL, FULL_SHOT_ASK
    return "", ""


