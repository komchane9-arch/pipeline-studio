_IS_CONS = re.compile(f"[{_CONS}]")
# ค่าปรับของพยางค์ที่เป็นพยัญชนะลอยเดี่ยว — สูงพอให้แพ้ทางที่ไม่มีเลย
# แต่ไม่ห้าม เพราะ "สบาย" = ส + บาย ก็มีลอยเดี่ยวจริงๆ
_ALONE_PENALTY = 40

# ค่าปรับของพยางค์ที่มีไม้หันอากาศแต่ไม่มีตัวสะกดเขียนไว้
# สูงกว่าค่าปรับพยัญชนะลอยเดี่ยว เพราะผิดกฎการเขียนไทยชัดกว่า
# แต่ยังไม่ห้ามขาด เพื่อให้คำยืมอย่าง อัตโนมัติ แบ่งออกได้
_HAN_NO_FINAL_PENALTY = _ALONE_PENALTY * 3

# **อักษรนำ** — พยัญชนะที่ขึ้นต้นคำแล้วออกเสียงสระอะสั้นๆ โดยไม่ต้องเขียนสระ
# (ส-บาย · ผ-นัง · ข-นม · ต-ลาด) พยางค์แบบนี้เป็นเรื่องปกติมากในภาษาไทย
# จึง **ไม่ควรโดนค่าปรับ** ต่างจากพยัญชนะลอยเดี่ยวตัวอื่นที่มักแปลว่าแยกผิด
#
# ไม่มีรายการนี้ "ติดผนัง" จะถูกแยกเป็น ติ-ดผ-นัง และ "ความสบาย" เป็น ควา-มส-บาย
# เพราะตัวเลือกที่ผิดไม่มีพยัญชนะลอยเดี่ยวเลย จึงได้คะแนนดีกว่า
_LEADERS = "ขคฉถผฝสศษหอกจตปพท"

_SYL_COST = 10


def split_syllables(word: str) -> list[str]:
    """แยกคำไทยก้อนหนึ่งเป็นพยางค์ — แยกไม่ลงคืนคำเดิมทั้งก้อน

    >>> split_syllables("ทำงาน")
    ['ทำ', 'งาน']
    """
    text = word or ""
    size = len(text)
    if size < 2:
        return [text] if text else []

    # **ทำไมต้องให้คะแนน ไม่ใช่เอาทางแรกที่แยกลงตัว** — คำไทยแยกได้หลายทาง
    # และทางที่เจอก่อนมักไม่ใช่ทางที่ถูก
    #
    #     ผ้าขนแกะ   ทางแรกที่เจอ = ผ้าข + น + แกะ  (มี น ลอยเดี่ยว)
    #                ทางที่ถูก     = ผ้า + ขน + แกะ
    #
    # ทั้งสองทางแยกลงตัวเหมือนกัน ต่างกันแค่ทางแรกมีพยัญชนะลอยเดี่ยว
    # จึงคิดค่าปรับให้พยางค์แบบนั้น แล้วเลือกทางที่ค่ารวมน้อยที่สุด
    #
    # แต่ **พยางค์ลอยเดี่ยวไม่ใช่เรื่องผิดเสมอไป** — "สบาย" คือ ส + บาย จริงๆ
    # ค่าปรับจึงต้องเป็นการหักคะแนน ไม่ใช่การห้าม
    # ---- แบ่งสองรอบ: เข้มก่อน ผ่อนทีหลัง (30 ส.ค. 2569) --------------------
    #
    # รอบแรกใช้กฎเข้ม "ไม้หันอากาศต้องมีตัวสะกด" ซึ่งถูกกับคำไทยแท้
    # แบ่งไม่ออกค่อยลองรอบสองที่ผ่อนกฎนั้นเป็นการหักคะแนนแทน
    #
    # **ทำไมต้องสองรอบ ไม่ใช่ผ่อนไปเลย** ผ่อนตั้งแต่รอบแรกทำให้คำที่เคยแบ่ง
    # ถูกอยู่แล้วเปลี่ยนไปแบบแย่ลงได้ วัดจริงกับบทพูด 1,197 คำ:
    #     ปรับองศา   แบ่งไม่ออก → ปรั-บอง-ศา   (ที่ถูกคือ ปรับ-อง-ศา)
    #     รับรองว้าว แบ่งไม่ออก → รั-บรอง-ว้าว  (ที่ถูกคือ รับ-รอง-ว้าว)
    # สองรอบจึงได้ทั้งสองอย่าง: ของเดิมไม่เปลี่ยน และของที่เคยแบ่งไม่ออกได้ขีด
    #
    # **ขีดที่เพี้ยนยังดีกว่าไม่มีขีดเลย** เพราะไม่มีขีด = Veo ไม่ได้คำอ่าน
    # ทั้งฉาก ส่วนขีดเพี้ยนอย่างน้อยยังบอกจังหวะพยางค์ให้ได้
    for loose in (False, True):
        picked = _solve_word(text, size, loose)
        if picked and len(picked) > 1:
            return picked
    return picked if picked else [text]


def _solve_word(text: str, size: int, loose: bool) -> list[str]:
    """แบ่งพยางค์หนึ่งรอบ — `loose` = ผ่อนกฎไม้หันอากาศเป็นการหักคะแนน"""
    cache: dict[int, tuple[int, list[str]] | None] = {}

    def solve(start: int) -> tuple[int, list[str]] | None:
        if start >= size:
            return (0, [])
        if start in cache:
            return cache[start]
        cache[start] = None                    # กันวนซ้ำตำแหน่งเดิม
        winner: tuple[int, list[str]] | None = None
        for pattern in (_SYL_CLOSED, _SYL_OPEN, _SYL_MIN, _SYL_BARE):
            found = pattern.match(text, start)
            if not found or found.end() == start:
                continue
            piece = found.group(0)
            # พยางค์ที่ไม่มีทั้งสระเขียนและตัวสะกด = พยัญชนะลอยเดี่ยว
            # (พยางค์ที่ไม่มีสระแต่มีตัวสะกดเป็นเรื่องปกติมาก — คง · ขน · นก)
            # **ไม้หันอากาศต้องมีตัวสะกดเสมอ** (ยกเว้นสระ ัว) — เป็นกฎการเขียน
            # ภาษาไทย ไม่ใช่การเดา "นั" เฉยๆ ไม่มีในภาษา ต้องเป็น นัก นัด นั่ง
            # ไม่มีกฎนี้ "นั่งสบาย" จะถูกแยกเป็น นั่-งส-บาย
            # **ไม้หันอากาศไม่มีตัวสะกด = หักคะแนนหนัก ไม่ใช่ห้ามขาด**
            # (เปลี่ยนจากห้ามขาดเป็นหักคะแนน 30 ส.ค. 2569)
            #
            # กฎ "ไม้หันอากาศต้องมีตัวสะกด" จริงกับคำไทยแท้ แต่**ไม่จริงกับ
            # คำยืมบาลี-สันสกฤต** ที่พยัญชนะตัวเดียวทำหน้าที่สองพยางค์
            #     อัตโนมัติ = อัต-โน-มั-ติ   ← "มั" ไม่มีตัวสะกดเขียนไว้
            #     ต ตัวเดียวเป็นทั้งตัวสะกดของ "มั" และตัวต้นของ "ติ"
            #
            # ห้ามขาดแล้วทั้งคำแบ่งไม่ออก → ตกไปทางถอย "คืนทั้งก้อน" →
            # **บทพูดไม่มีคำอ่านส่งให้ Veo ทั้งฉาก** ซึ่งแพงกว่าการแบ่งเพี้ยน
            #
            # หักคะแนนหนักแทน ทางที่มีตัวสะกดจึงยังชนะเสมอเมื่อมีให้เลือก
            # (`นั่งสบาย` ยังได้ นั่ง-ส-บาย ไม่ใช่ นั่-งส-บาย) แต่ตอนไม่มีทางอื่น
            # ก็ยังแบ่งออกได้ ดีกว่าไม่ได้อะไรเลย
            han_no_final = (pattern in (_SYL_OPEN, _SYL_MIN) and "ั" in piece
                            and not piece.endswith("ว"))
            if han_no_final and not loose:
                continue                       # รอบเข้ม: ห้ามขาดเหมือนเดิม
            alone = pattern is not _SYL_CLOSED and not _HAS_VOWEL.search(piece)
            if alone and found.end() >= size:
                continue                       # ลอยเดี่ยวท้ายคำ อ่านไม่ออกแน่ๆ
            rest = solve(found.end())
            if rest is None:
                continue
            score = rest[0] + _SYL_COST
            if alone and piece[:1] not in _LEADERS:
                score += _ALONE_PENALTY
            if han_no_final:
                score += _HAN_NO_FINAL_PENALTY
            if winner is None or score < winner[0]:
                winner = (score, [piece] + rest[1])
        cache[start] = winner
        return winner

    found = solve(0)
    return found[1] if found else []


