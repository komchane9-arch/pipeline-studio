# ตัดเฉพาะขีดที่ขนาบด้วยอักษรไทยทั้งสองข้าง
#
# **ห้ามตัดขีดทุกตัว** — คำอย่าง `USB-C` `5-in-1` `Type-C` มีขีดที่เป็นส่วนหนึ่ง
# ของชื่อจริง ตัดทิ้งแล้วกลายเป็น `USBC` ซึ่งผิดและอ่านออกเสียงคนละอย่าง
_SYLLABLE_DASH_RE = re.compile(r"(?<=[฀-๿])-(?=[฀-๿])")


def plain_text(line: str) -> str:
    """คำอ่านคั่นพยางค์ → ประโยคปกติ สำหรับเอาไปโชว์/ให้คนแก้

    `ชาร์จ-ไว-หก-สิบ-วัตต์ รอ-ไม่-นาน-เลย` → `ชาร์จไวหกสิบวัตต์ รอไม่นานเลย`

    เว้นวรรคเดิมคงไว้ทุกตัว เพราะนั่นคือจังหวะหยุดที่ตั้งใจ
    """
    return _SYLLABLE_DASH_RE.sub("", str(line or "")).strip()


def plain_lines(lines) -> list[str]:
    """ทั้งชุดทีเดียว"""
    return [plain_text(line) for line in (lines or [])]


def has_reading(line: str) -> bool:
    """บรรทัดนี้เขียนเป็นคำอ่านคั่นพยางค์แล้วหรือยัง"""
    return bool(_SYLLABLE_DASH_RE.search(str(line or "")))


def same_words(reading: str, plain: str) -> bool:
    """คำอ่านบรรทัดนี้ตรงกับประโยคปกติไหม — **ตัวกันคำเพี้ยน**

    ใช้ตรวจว่า AI ที่ใส่ขีดให้ **ไม่ได้แอบเปลี่ยนคำ** ระหว่างทาง
    เทียบโดยตัดขีดกับช่องว่างออกให้หมดแล้วดูว่าตัวอักษรเหลือเท่ากันไหม
    """
    strip = lambda s: plain_text(s).replace(" ", "")
    return strip(reading) == strip(plain)
