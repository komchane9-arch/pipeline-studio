#   3. คำแทนต้องสั้นกว่าหรือเท่าเดิม ไม่งั้นไปกินโควตาตัวอักษรของบทพูด
# **เรียงจากวลียาวไปสั้น** — จับวลีที่ยาวกว่าก่อนเสมอ ไม่งั้นจะได้คำซ้อนกัน
