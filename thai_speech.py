#     `อ` ที่ตามด้วยสระบน/ล่าง เป็น **พยัญชนะต้น** ของพยางค์ถัดไป (อบ-อุ่น)
#     `อ` ที่ตามด้วยพยัญชนะ เป็น **สระ** ของพยางค์นี้ (มิ-นิ-มอล)
