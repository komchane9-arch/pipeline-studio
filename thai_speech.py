# ตัวสะกด — หยิบได้ต่อเมื่อตัวถัดไป **ไม่ใช่สระ** ไม่งั้นจะไปแย่งพยัญชนะต้น
# ของพยางค์ถัดไปมา (ทำ|งาน จะกลายเป็น ทำง|าน)
