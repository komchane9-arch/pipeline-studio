# ทำ "คำอ่าน" จริง ไม่ใช่แค่ตัดพยางค์ (เจ้าของสอนเอง 29 ส.ค. 2569)
# ---------------------------------------------------------------------------
#
# เจ้าของแก้ให้: *"ผะ-หนัง ต้องแบบนี้"* และ *"ตะ-หลาด"*
# แล้วสั่งว่า *"ศึกษาเรื่อง อักษร หอนำ รหัน เพิ่มในเน็ตมา"*
#
# ตัดพยางค์ได้ `ผ-นัง` ยังไม่พอ เพราะ **ตัวอ่านเสียงไม่รู้ว่า ผ ตัวเดียวอ่านว่าอะไร**
# ต้องเขียนสระอะที่ไม่ได้เขียนไว้ให้เห็น และต้องบอกเสียงวรรณยุกต์ของพยางค์หลังด้วย
#
#   ผนัง   →  ผะ-หนัง     ผ เป็นอักษรสูง คุมเสียง นัง ให้เป็นเสียงจัตวาแบบ หนัง
#   ตลาด   →  ตะ-หลาด     ต เป็นอักษรกลาง คุมเสียง ลาด เหมือนกัน
#   ขนม    →  ขะ-หนม
#   สบาย   →  สะ-บาย      บ เป็นอักษรกลาง ไม่ใช่อักษรต่ำเดี่ยว จึง **ไม่ใส่ ห**
#
# **สามชั้นของภาษาไทยที่ต้องรู้**
#
#   อักษรนำ   พยัญชนะตัวหน้าที่ออกเสียงสระอะสั้นๆ โดยไม่ได้เขียนสระไว้
#   ห นำ      ห ที่ไม่ออกเสียง แต่ไปคุมเสียงตัวหลัง (หนู · หมา · หลัง)
#             ตัวนี้ตัวแยกพยางค์รู้จักอยู่แล้ว ไม่ต้องแปลงอะไร
#   ร หัน     `รร` ที่อ่านเป็นสระอะ + น (บรรจุ = บัน-จุ) หรือเป็นตัวสะกด
#             ถ้ามีตัวสะกดตามหลังอยู่แล้ว (กรรม = กัม)

# อักษรสูง — ข ฃ ฉ ฐ ถ ผ ฝ ศ ษ ส ห
_HIGH = "ขฃฉฐถผฝศษสห"
# อักษรกลาง — ก จ ฎ ฏ ด ต บ ป อ
_MID = "กจฎฏดตบปอ"
# อักษรต่ำเดี่ยว — ตัวที่ไม่มีคู่เสียงสูง จึงต้องยืม ห หรืออักษรนำมาคุมเสียง
_LOW_ALONE = "งญณนมยรลวฬ"

# ตัวหลัง `รร` เป็น**ตัวสะกด**ก็ต่อเมื่อไม่มีสระตามหลัง (กรรม = กัม)
# ถ้ามีสระตามหลัง แปลว่าเป็นพยัญชนะต้นของพยางค์ถัดไป (บรรจุ = บัน-จุ)
_RAHAN_RE = re.compile(
    f"([{_CONS}])รร([{_CONS}](?![{_FOLLOW}{_UPPER}]))?")


def _rahan(word: str) -> str:
    """แปลง ร หัน (`รร`) ให้เป็นรูปที่อ่านออก

    มีตัวสะกดตามหลัง → `รร` ทำหน้าที่สระอะ      กรรม  → กัม
    ไม่มีตัวสะกด      → `รร` อ่านเป็น สระอะ + น   บรรจุ → บันจุ
    """
    def one(found: "re.Match[str]") -> str:
        head, tail = found.group(1), found.group(2)
        return f"{head}ั{tail}" if tail else f"{head}ัน"
    return _RAHAN_RE.sub(one, word or "")


def reading(word: str) -> list[str]:
    """คำอ่านของคำไทยคำหนึ่ง แยกเป็นพยางค์ที่อ่านออกเสียงได้ตรง

    >>> reading("ผนัง")
    ['ผะ', 'หนัง']
    >>> reading("ตลาด")
    ['ตะ', 'หลาด']
    >>> reading("สบาย")
    ['สะ', 'บาย']
    """
    parts = split_syllables(_rahan(word))
    out: list[str] = []
    for index, piece in enumerate(parts):
        nxt = parts[index + 1] if index + 1 < len(parts) else ""
        # พยัญชนะลอยเดี่ยว = อักษรนำ ต้องเขียนสระอะให้เห็น
        if len(piece) == 1 and piece in _HIGH + _MID + _LOW_ALONE and nxt:
            out.append(piece + "ะ")
            # อักษรสูง/กลาง คุมเสียงอักษรต่ำเดี่ยวตัวหลัง — เขียน ห นำให้เห็น
            if piece in _HIGH + _MID and nxt[:1] in _LOW_ALONE:
                parts[index + 1] = "ห" + nxt
            continue
        out.append(piece)
    return out


def spell_out(text: str) -> str:
    """เปลี่ยนคำไทยทุกคำในข้อความให้เป็นคำอ่านคั่นด้วยขีด

    ภาษาอังกฤษ ตัวเลข และเครื่องหมาย **ไม่ถูกแตะ** — Veo อ่านของพวกนั้น
    ได้อยู่แล้ว และการใส่ขีดในชื่อรุ่นจะทำให้อ่านผิดกว่าเดิม
    """
    def one(match: re.Match[str]) -> str:
        parts = reading(match.group(0))
        return "-".join(parts) if len(parts) > 1 else match.group(0)

    return THAI_RUN_RE.sub(one, text or "")


