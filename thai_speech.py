# คำอ่าน — แยกพยางค์ด้วยขีด เพื่อให้ Veo ออกเสียงถูก
# ---------------------------------------------------------------------------
#
# **เจ้าของสั่งไว้ 29 ส.ค. 2569** — *"ให้ใส่เป็นคำอ่านแทน ตอนพูดทุกคำ
# เช่น ทำงาน เป็น ทำ-งาน"*
#
# **ทำไมถึงต้องมี** ตรวจคลิป 26 ใบพบว่า **11 ใบออกเสียงคำผิด (42%)** และคำที่
# ผิดเป็นแบบเดียวกันหมด คือ Veo มองคำไทยเป็นก้อนเดียวแล้วเดาเสียงผิด
#
#     ทำงาน   → "ทวาร"      (เจอ 2 ใบ · ความหมายเสียหายหนัก)
#     ติดตั้ง  → "ติ๊กตั่ง"
#     ไวรัส    → "ไวลัก"
#     แอช      → "แอดซิ"
#
# ใส่ขีดคั่นพยางค์แล้ว Veo เห็นขอบเขตพยางค์ชัด ไม่ต้องเดาเอง
#
# ⚠️ **ไม่มีไลบรารีตัดคำไทยในเครื่องนี้** (ไม่มีทั้ง pythainlp และ ssg)
# จึงเขียนกฎเอง — และเพราะเขียนเอง **จึงต้องยอมแพ้ให้เป็น** คือถ้าแยกไม่ลงตัว
# ให้คืนคำเดิมทั้งก้อน ดีกว่าแยกผิดแล้วทำให้อ่านเพี้ยนกว่าเดิม
#
# **หลักการของตัวแยก** ไล่หาพยางค์จากซ้ายไปขวาแบบ **ถอยหลังได้**
# ถ้าตัดแบบหนึ่งแล้วส่วนที่เหลือแยกไม่ลง จะถอยมาลองแบบที่สั้นกว่า
# ตัวอย่างที่ต้องมีการถอยหลังถึงจะถูก:
#
#     ผ้าขนแกะ   ตัดตรงๆ ได้ "ผ้าข" แล้วเหลือ "นแกะ" ซึ่ง น ลอยเดี่ยวหน้าสระ แ
#                = แยกไม่ลง → ถอยมาเป็น "ผ้า" แล้วได้ ผ้า-ขน-แกะ ถูกต้อง

_LEAD = "เ-ไ"                       # สระหน้า เ แ โ ใ ไ
_CONS = "ก-ฮ"                       # พยัญชนะ ก-ฮ
_UPPER = "ัิ-ฺ็ํ"    # สระบน/ล่าง ั ิ ี ึ ื ุ ู ็ ํ
_TONE = "่-๋"                       # วรรณยุกต์ ่ ้ ๊ ๋
_FOLLOW = "ะาำๅ"          # สระหลัง ะ า ำ ๅ
_KARAN = "์"                             # ตัวการันต์ ์
_O = "อ"                                 # อ ที่ทำหน้าที่เป็นสระ
_SARA_A = "ะ"                            # ะ
_MAI = "ๆ"                               # ๆ

# พยัญชนะต้น — รวมตัวนำที่ไม่ออกเสียง (อย่า · หนู · หลัง) และตัวควบกล้ำ (ปลา · ความ)
# ควบกล้ำมีชุดจำกัด ไม่ใช่พยัญชนะอะไรก็ควบ ร ล ว ได้
# (ถ้าปล่อยกว้าง "ไวรัส" จะถูกอ่านเป็นควบ "วร" แล้วไม่ยอมแยกพยางค์เลย)
_CLUSTER_HEAD = "กขคฆตทปผพภบดฟ"
_INIT = (
    f"(?:{_O}ย"
    "|ห[งญณนมยรลวฬ]"
    f"|[{_CLUSTER_HEAD}][รลว]"
    f"|[{_CONS}])"
)
# ตัวสะกด — หยิบได้ต่อเมื่อตัวถัดไป **ไม่ใช่สระ** ไม่งั้นจะไปแย่งพยัญชนะต้น
# ของพยางค์ถัดไปมา (ทำ|งาน จะกลายเป็น ทำง|าน)
# `อ` ปกติทำหน้าที่สระ (มิ-นิ-มอล) จึงห้ามหยิบตัวสะกดข้ามมัน
# **ยกเว้น `อย`** ซึ่งเป็นตัวนำไม่ออกเสียงของพยางค์ถัดไป (ทุก-อย่าง)
_NOT_VOWEL_NEXT = f"(?!(?:[{_FOLLOW}{_UPPER}]|{_O}(?!ย)))"
# ตัวสะกดไทยไม่มี ห อ ฮ เลย — ปล่อยให้เป็นตัวสะกดได้จะแย่งตัวนำ
# ของพยางค์ถัดไป ("ประหยัด" จะกลายเป็น ประห-ยัด)
_FINAL_CONS = "ก-สฬ"
# ตัวการันต์ตามด้วยตัวสะกดอีกตัวได้ — คำยืมอังกฤษเป็นแบบนี้เยอะ
# (ชาร์จ = ช + า + ร์ + จ  ถ้าไม่เผื่อ จะได้ ชาร์-จ ซึ่ง จ ลอยเดี่ยว)
# **ห้ามหยิบตัวสะกดถ้าทำให้ควบกล้ำของพยางค์ถัดไปขาด**
#
#     สะดวก    ถ้าหยิบ ด เป็นตัวสะกด จะได้ สะด-วก  ← ฉีก ดว ออกจากกัน
#                ไม่หยิบ จะได้ สะ-ดวก  ← ถูก
#     ปรับระดับ  หยิบ บ เป็นตัวสะกดได้ เพราะ ร ตัวถัดไปมีสระ ะ ของตัวเอง
#                จึงไม่ใช่ควบกล้ำ ได้ ปรับ-ระ-ดับ  ← ถูก
#
# ต่างกันตรง "ตัวหลัง ร ล ว เป็นสระหรือไม่" เท่านั้น
_KEEP_CLUSTER = f"(?![{_CLUSTER_HEAD}][รลว](?![{_FOLLOW}{_UPPER}{_O}]))"
_FINAL = (
    f"(?:[{_FINAL_CONS}]{_KARAN}[{_FINAL_CONS}]{_NOT_VOWEL_NEXT}"
    f"|[{_FINAL_CONS}]{_KARAN}"
    f"|{_KEEP_CLUSTER}[{_FINAL_CONS}]{_NOT_VOWEL_NEXT})"
)
# `ย` ตรงกลางเป็นส่วนหนึ่งของสระ เ-ีย (เบียง · เตียง · เดียว) ไม่ใช่ตัวสะกด
# ไม่เผื่อช่องนี้ไว้ "เตียงนอน" จะถูกแยกเป็น เตีย-ง-นอน
_BODY = (
    f"[{_LEAD}]?{_INIT}[{_TONE}]?[{_UPPER}]*[{_TONE}]?ย?"
    f"{_O}?[{_FOLLOW}]?[{_TONE}]?"
)

_SYL_CLOSED = re.compile(f"{_BODY}{_FINAL}[{_TONE}]?[{_SARA_A}]?[{_MAI}]?")
_SYL_OPEN = re.compile(f"{_BODY}[{_SARA_A}]?[{_MAI}]?")
_SYL_BARE = re.compile(f"{_INIT}(?=[{_CONS}])")
_HAS_VOWEL = re.compile(f"[{_LEAD}{_UPPER}{_FOLLOW}{_O}{_SARA_A}]")
_IS_CONS = re.compile(f"[{_CONS}]")
# ค่าปรับของพยางค์ที่เป็นพยัญชนะลอยเดี่ยว — สูงพอให้แพ้ทางที่ไม่มีเลย
# แต่ไม่ห้าม เพราะ "สบาย" = ส + บาย ก็มีลอยเดี่ยวจริงๆ
_ALONE_PENALTY = 40

_SYL_COST = 10


def split_syllables(word: str) -> list[str]:
    """แยกคำไทยก้อนหนึ่งเป็นพยางค์ — แยกไม่ลงคืนคำเดิมทั้งก้อน

    >>> split_syllables("ทำงาน")
    ['ทำ', 'งาน']
    """
    text = word or ""
    size = len(text)
    if size < 2:
        return [text] if text else []

    # **ทำไมต้องให้คะแนน ไม่ใช่เอาทางแรกที่แยกลงตัว** — คำไทยแยกได้หลายทาง
    # และทางที่เจอก่อนมักไม่ใช่ทางที่ถูก
    #
    #     ผ้าขนแกะ   ทางแรกที่เจอ = ผ้าข + น + แกะ  (มี น ลอยเดี่ยว)
    #                ทางที่ถูก     = ผ้า + ขน + แกะ
    #
    # ทั้งสองทางแยกลงตัวเหมือนกัน ต่างกันแค่ทางแรกมีพยัญชนะลอยเดี่ยว
    # จึงคิดค่าปรับให้พยางค์แบบนั้น แล้วเลือกทางที่ค่ารวมน้อยที่สุด
    #
    # แต่ **พยางค์ลอยเดี่ยวไม่ใช่เรื่องผิดเสมอไป** — "สบาย" คือ ส + บาย จริงๆ
    # ค่าปรับจึงต้องเป็นการหักคะแนน ไม่ใช่การห้าม
    cache: dict[int, tuple[int, list[str]] | None] = {}

    def solve(start: int) -> tuple[int, list[str]] | None:
        if start >= size:
            return (0, [])
        if start in cache:
            return cache[start]
        cache[start] = None                    # กันวนซ้ำตำแหน่งเดิม
        winner: tuple[int, list[str]] | None = None
        for pattern in (_SYL_CLOSED, _SYL_OPEN, _SYL_BARE):
            found = pattern.match(text, start)
            if not found or found.end() == start:
                continue
            piece = found.group(0)
            # พยางค์ที่ไม่มีทั้งสระเขียนและตัวสะกด = พยัญชนะลอยเดี่ยว
            # (พยางค์ที่ไม่มีสระแต่มีตัวสะกดเป็นเรื่องปกติมาก — คง · ขน · นก)
            alone = pattern is not _SYL_CLOSED and not _HAS_VOWEL.search(piece)
            if alone and found.end() >= size:
                continue                       # ลอยเดี่ยวท้ายคำ อ่านไม่ออกแน่ๆ
            rest = solve(found.end())
            if rest is None:
                continue
            score = rest[0] + _SYL_COST
            if alone:
                score += _ALONE_PENALTY
            if winner is None or score < winner[0]:
                winner = (score, [piece] + rest[1])
        cache[start] = winner
        return winner

    picked = solve(0)
    return picked[1] if picked else [text]


def spell_out(text: str) -> str:
    """เปลี่ยนคำไทยทุกคำในข้อความให้เป็นคำอ่านคั่นด้วยขีด

    ภาษาอังกฤษ ตัวเลข และเครื่องหมาย **ไม่ถูกแตะ** — Veo อ่านของพวกนั้น
    ได้อยู่แล้ว และการใส่ขีดในชื่อรุ่นจะทำให้อ่านผิดกว่าเดิม
    """
    def one(match: re.Match[str]) -> str:
        parts = split_syllables(match.group(0))
        return "-".join(parts) if len(parts) > 1 else match.group(0)

    return THAI_RUN_RE.sub(one, text or "")


def speech_ready(text: str, level: int = 1, spell: bool = False) -> str:
    """ทำบทให้พร้อมให้ Veo อ่าน — เรียกได้ทั้งกับบทพูดล้วนและกับ prompt ทั้งก้อน

    ปลอดภัยกับข้อความอังกฤษด้วย (แค่ตัด ! ? ซึ่งไม่กระทบคำสั่งกล้อง/แสง)

    `spell=True` = ใส่คำอ่านคั่นพยางค์ด้วย **ใช้กับบรรทัดเสียงพูดเท่านั้น**
    ห้ามใช้กับ prompt ทั้งก้อน เพราะคำไทยที่อยู่ในคำบรรยายภาพไม่ได้ถูกอ่านออกเสียง
    การใส่ขีดตรงนั้นมีแต่ทำให้ Veo สับสนว่าจะวาดอะไร
    """
    out = pace(strip_shouty(text), level)
    return spell_out(out) if spell else out


